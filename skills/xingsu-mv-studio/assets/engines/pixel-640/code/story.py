COLS = ['镜号', '起', '止', '段落', '歌词', '画面', '动作与触发点']


def write_docs(path_md, path_csv):
    import csv
    with open(path_csv, 'w', newline='', encoding='utf-8-sig') as f:
        w = csv.writer(f)
        w.writerow(COLS)
        for r in SHOTS:
            w.writerow([r[0], '%.2f' % r[1], '%.2f' % r[2]] + list(r[3:]))
    with open(path_md, 'w', encoding='utf-8') as f:
        f.write('# 下雨了 · 像素 MV 分镜（0:00–2:28）\n\n| ' + ' | '.join(COLS) + ' |\n|' + '---|' * len(COLS) + '\n')
        for r in SHOTS:
            f.write('| %s | %.2f | %.2f | %s | %s | %s | %s |\n' % r)


if __name__ == '__main__':
    write_docs(_os.path.join(_ROOT, 'out/storyboard.md'), _os.path.join(_ROOT, 'out/storyboard.csv'))
    print(len(SHOTS), 'shots')
