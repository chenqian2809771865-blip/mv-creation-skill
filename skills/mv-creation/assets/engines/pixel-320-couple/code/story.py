def write_storyboard(path_csv, path_md):
    import csv
    head = ['镜号', '起', '止', '段落', '歌词', '画面', '动作/镜头', '转场', '实现']
    with open(path_csv, 'w', newline='', encoding='utf-8-sig') as f:
        w = csv.writer(f)
        w.writerow(head)
        for s in SHOTS:
            w.writerow([s[0], '%.2f' % s[1], '%.2f' % s[2]] + list(s[3:]))
    with open(path_md, 'w', encoding='utf-8') as f:
        f.write('# 《晴天》管弦乐版 · 开场样片分镜\n\n| ' + ' | '.join(head) + ' |\n|' + '---|' * len(head) + '\n')
        for s in SHOTS:
            f.write('| %s | %.2f | %.2f | %s |\n' % (s[0], s[1], s[2], ' | '.join(s[3:])))
